#!/usr/bin/env node
/**
 * Builds the French, German and Spanish versions of the site before `next build`.
 *
 * English is the source: pages live in app/en (URLs /en/...). For each other locale this script writes
 * a translated copy of that route tree to app/<locale>/ (URLs /fr/..., /de/..., /es/...) and of the shared
 * code and content to .i18n/<locale>/. In each copy:
 *   - visible English strings (JSX text, prose attributes, prose string and template literals) are replaced
 *     from i18n/<locale>.json (English source -> translation);
 *   - `@/components/...` style imports point at the locale's copy;
 *   - config/locale.ts exports the locale code, so links (localePath), <html lang>, canonical and
 *     hreflang follow automatically;
 *   - journal posts come from i18n/content/<locale>/journal/*.mdx.
 * Everything is pre-rendered; no translation code ships to the browser.
 *
 *   node scripts/i18n-build.mjs            generate (runs automatically before dev and build)
 *   node scripts/i18n-build.mjs extract    write i18n/strings.json (every candidate string, with where it is used)
 *   node scripts/i18n-build.mjs missing    count strings with no translation per locale (add --list to print them)
 *
 * A file containing the comment `i18n-skip-strings` is copied with its imports rewritten only.
 * A dictionary value equal to its key leaves the text unchanged (names, brand terms).
 * Generated folders are git-ignored.
 */
import fs from "node:fs";
import path from "node:path";
import { extract, translateSource, walk } from "./i18n-core.mjs";

const ROOT = process.cwd();
const LOCALES = ["fr", "de", "es"];
const INTL = { fr: "fr-FR", de: "de-DE", es: "es-ES" };
const OG = { fr: "fr_FR", de: "de_DE", es: "es_ES" };
const EN_APP = path.join(ROOT, "app", "en");
const SHARED = ["components", "lib", "data", "config", "dictionaries", "content"];
/** Internal pages that are not translated (noindex tools). */
const SKIP_ROUTES = ["design-system"];
const CODE = /\.(tsx?|jsx?|mjs)$/;
const SKIP_MARK = "i18n-skip-strings";

const isSkippedRoute = (f) => SKIP_ROUTES.some((r) => f.startsWith(path.join(EN_APP, r) + path.sep));

function importRewriteFor(locale, fromFile, outFile) {
  return (spec) => {
    for (const d of SHARED) {
      if (spec === `@/${d}` || spec.startsWith(`@/${d}/`)) return spec.replace(`@/${d}`, `@/.i18n/${locale}/${d}`);
    }
    if (spec.startsWith(".")) {
      // Relative import: if the target is not copied alongside, point back to the original.
      const target = path.resolve(path.dirname(fromFile), spec);
      const copied = target.startsWith(EN_APP + path.sep) || SHARED.some((d) => target.startsWith(path.join(ROOT, d) + path.sep));
      if (!copied) {
        let rel = path.relative(path.dirname(outFile), target).split(path.sep).join("/");
        if (!rel.startsWith(".")) rel = "./" + rel;
        return rel;
      }
    }
    return spec;
  };
}

function special(locale) {
  return (text, node, s) => {
    if (s.kind === "str") {
      if (/^en-(GB|US)$/.test(text)) return JSON.stringify(INTL[locale]);
      if (text === "en_GB") return JSON.stringify(OG[locale]);
    }
    return null;
  };
}

const loadDict = (l) => {
  const f = path.join(ROOT, "i18n", `${l}.json`);
  return fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, "utf8")) : {};
};

function header(rel) {
  return `// GENERATED by scripts/i18n-build.mjs from ${rel}. Do not edit.\n`;
}

function copyTree(fromDir, toDir, locale, dict) {
  for (const f of walk(fromDir)) {
    if (fromDir === EN_APP && isSkippedRoute(f)) continue;
    const rel = path.relative(fromDir, f);
    const out = path.join(toDir, rel);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    if (CODE.test(f) && !f.endsWith(".d.ts")) {
      const src = fs.readFileSync(f, "utf8");
      let text = translateSource(f, {
        dict: src.includes(SKIP_MARK) ? {} : dict,
        fileKey: path.relative(ROOT, f).split(path.sep).join("/"),
        importRewrite: importRewriteFor(locale, f, out),
        special: special(locale),
      });
      // Typed route helpers: PageProps<"/en/..."> -> PageProps<"/fr/...">
      text = text.replace(/((?:Page|Layout)Props<")\/en(?=["/])/g, `$1/${locale}`);
      const directive = text.match(/^\s*(["'])use (client|server)\1;?\s*\n/);
      fs.writeFileSync(out, directive ? directive[0] + header(path.relative(ROOT, f)) + text.slice(directive[0].length) : header(path.relative(ROOT, f)) + text);
    } else {
      fs.copyFileSync(f, out);
    }
  }
}

const sourceFiles = () => [
  ...walk(EN_APP, (f) => CODE.test(f) && !isSkippedRoute(f)),
  ...SHARED.flatMap((d) => walk(path.join(ROOT, d), (f) => CODE.test(f) && !f.endsWith(".d.ts") && !fs.readFileSync(f, "utf8").includes(SKIP_MARK))),
];

const mode = process.argv[2] || "build";
if (mode === "extract") {
  const map = extract(sourceFiles());
  const obj = Object.fromEntries([...map.entries()].sort((a, b) => a[1][0].localeCompare(b[1][0])).map(([k, v]) => [k, v]));
  fs.mkdirSync(path.join(ROOT, "i18n"), { recursive: true });
  fs.writeFileSync(path.join(ROOT, "i18n", "strings.json"), JSON.stringify(obj, null, 2) + "\n");
  console.log(`i18n: ${map.size} strings -> i18n/strings.json`);
} else if (mode === "missing") {
  const all = [...extract(sourceFiles()).keys()];
  let total = 0;
  for (const l of LOCALES) {
    const d = loadDict(l);
    const miss = all.filter((s) => d[s] == null);
    total += miss.length;
    console.log(`${l}: ${miss.length} missing`);
    if (process.argv[3] === "--list") miss.forEach((s) => console.log("  " + JSON.stringify(s)));
  }
  process.exit(total && process.argv.includes("--strict") ? 1 : 0);
} else {
  fs.rmSync(path.join(ROOT, ".i18n"), { recursive: true, force: true });
  for (const l of LOCALES) {
    const dict = loadDict(l);
    fs.rmSync(path.join(ROOT, "app", l), { recursive: true, force: true });
    copyTree(EN_APP, path.join(ROOT, "app", l), l, dict);
    for (const d of SHARED) copyTree(path.join(ROOT, d), path.join(ROOT, ".i18n", l, d), l, dict);
    // Translated journal posts replace the English copies.
    const content = path.join(ROOT, "i18n", "content", l);
    if (fs.existsSync(content)) fs.cpSync(content, path.join(ROOT, ".i18n", l, "content"), { recursive: true });
    fs.writeFileSync(
      path.join(ROOT, ".i18n", l, "config", "locale.ts"),
      header("config/locale.ts") + `import type { Locale } from "./i18n";\n\nexport const locale: Locale = "${l}";\n`,
    );
  }
  console.log(`i18n: generated ${LOCALES.join(", ")}`);
}

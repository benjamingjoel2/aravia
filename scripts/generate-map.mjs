/**
 * Generates data/map.ts: the Arab-world map on the homepage contact panel.
 * Natural Earth via world-atlas (public domain), simplified and projected to a 1000 x 560 viewBox.
 *
 * Run: npm i --no-save world-atlas@2.0.2 topojson-client@3.1.0 topojson-simplify@3.0.3 d3-geo@3.1.1
 *      node scripts/generate-map.mjs
 */
import fs from 'fs';
import { feature } from 'topojson-client';
import { geoMercator, geoPath } from 'd3-geo';
import { presimplify, simplify } from 'topojson-simplify';
const topo0 = JSON.parse(fs.readFileSync('node_modules/world-atlas/countries-50m.json'));
const topo = simplify(presimplify(topo0), 0.04);
const all = feature(topo, topo.objects.countries).features;
const ids = {'682':'SA','784':'AE','634':'QA','414':'KW','048':'BH','512':'OM','400':'JO','818':'EG','504':'MA','788':'TN','012':'DZ'};
const covered = all.filter(f=>ids[f.id]);
console.log('found', covered.map(f=>ids[f.id]).join(','));
const W=1000,H=560;
const fc={type:'FeatureCollection',features:covered};
const proj=geoMercator().fitExtent([[24,24],[W-24,H-24]],fc);
const round=s=>s.replace(/(\d+)\.\d+/g,'$1').replace(/L(-?\d+),(-?\d+)(?=L\1,\2)/g,'');
proj.clipExtent([[0,0],[W,H]]); const path=geoPath(proj);
const inView=f=>{const b=path.bounds(f); return b[1][0]>-50&&b[0][0]<W+50&&b[1][1]>-50&&b[0][1]<H+50;};
const others=all.filter(f=>!ids[f.id]&&inView(f));
const cov={}; for(const f of covered) cov[ids[f.id]]=round(path(f));
const oth=round(others.map(f=>path(f)).join(''));
const out=`/** Generated by scripts/generate-map.mjs from Natural Earth (world-atlas 50m, public domain). Do not edit by hand. */
export const mapSize = { width: ${W}, height: ${H} } as const;

/** Countries Aravia covers, keyed by ISO code. */
export const coveredPaths: Record<string, string> = ${JSON.stringify(cov,null,2)};

/** Neighbouring countries, drawn as faint outlines for context. */
export const neighbourPaths = ${JSON.stringify(oth)};
`;
fs.writeFileSync('data/map.ts',out);
console.log('bytes',out.length);
